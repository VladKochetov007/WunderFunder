"""Build RESULTS.md from the fit logs in this folder (full-valid WP per epoch, fixed last epoch)."""
import re
from pathlib import Path

HERE = Path(__file__).parent
CONTROL = ("tt29_parent_s3 (Oct 29 control: since32, labels)", [0.67972, 0.68490, 0.68743, 0.68671])
NOTES = {line.split()[0]: " ".join(line.split()[2:]) or "recipe default" for line in (HERE / "queue.txt").read_text().splitlines() if line.strip()}
NOTES["l14_kd50_s3"] = "--distill tt29rep_fbc1k_s5 --distill-alpha 0.5"
rows = [(CONTROL[0], "seed 3, recipe default", CONTROL[1], True)]
for log in sorted(HERE.glob("l14_*.fit.log"), key=lambda p: p.stat().st_mtime):
    text = log.read_text()
    wps = [float(x) for x in re.findall(r'"weighted_pearson": ([0-9.]+)', text)]
    name = log.name.removesuffix(".fit.log")
    rows.append((name, NOTES.get(name, ""), wps, "SELECTED_FIXED" in text))
out = ["# Results (generated by make_results.py; full official valid, 1,873 sequences / 3,528,273 rows)", "",
       "| Cell | Change vs recipe | WP by epoch | Final | Δ vs seed-3 control | State |", "|---|---|---|---|---|---|"]
for name, note, wps, done in rows:
    final = f"{wps[-1]:.5f}" if done and wps else "—"
    delta = f"{wps[-1] - CONTROL[1][-1]:+.5f}" if done and wps and "_s3" in name and not name.startswith("tt29") else "—"
    out.append(f"| {name} | `{note}` | {' → '.join(f'{w:.5f}' for w in wps)} | {final} | {delta} | {'done' if done else 'running'} |")
out += ["", "Pending in queue order: " + ", ".join(n for n in NOTES if not (HERE / f"{n}.fit.log").exists()) + ".", "",
        "One seed per cell unless a seed-4 pair is listed; valid is repeatedly inspected development data."]
(HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
