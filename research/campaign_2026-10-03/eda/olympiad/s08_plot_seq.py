import pyarrow.parquet as pq, numpy as np, pandas as pd, matplotlib
matplotlib.use("Agg"); import matplotlib.pyplot as plt
pf = pq.ParquetFile("datasets/train.parquet")
df = pf.read_row_group(0).to_pandas()
sl = slice(0, 3000)
fig, ax = plt.subplots(7,1, figsize=(16,20), sharex=True)
for k in range(11): ax[0].plot(df[f"i0_p{k}"].values[sl], lw=.7, label=f"p{k}")
ax[0].legend(ncol=11, fontsize=7); ax[0].set_title("i0_p0..p10")
for k in range(11,22): ax[1].plot(df[f"i0_p{k}"].values[sl], lw=.7, label=f"p{k}")
ax[1].legend(ncol=11, fontsize=7); ax[1].set_title("i0_p11..p21")
for k in range(4): ax[2].plot(df[f"i0_dp{k}"].values[sl], lw=.7, label=f"dp{k}")
ax[2].legend(); ax[2].set_title("i0_dp")
for k in range(0,22,3): ax[3].plot(df[f"i0_v{k}"].values[sl], lw=.5, label=f"v{k}")
ax[3].legend(ncol=8, fontsize=7); ax[3].set_title("i0_v (subset)")
for k in range(8): ax[4].plot(df[f"a{k}"].values[sl], lw=.5, label=f"a{k}")
ax[4].legend(ncol=8, fontsize=7); ax[4].set_title("a0..a7")
ax[5].plot(df.t0.values[sl], label="t0"); ax[5].plot(df.t1.values[sl], label="t1"); ax[5].legend(); ax[5].set_title("targets")
for k in range(0,11,2): ax[6].plot(df[f"i1_p{k}"].values[sl], lw=.7, label=f"i1_p{k}")
ax[6].legend(ncol=6, fontsize=7); ax[6].set_title("i1_p (subset)")
plt.tight_layout(); plt.savefig("research/campaign_2026-10-03/eda/olympiad/f01_seq0_first3000.png", dpi=70)
