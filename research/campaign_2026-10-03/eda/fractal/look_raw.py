import numpy as np, pyarrow.parquet as pq, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
pf = pq.ParquetFile('datasets/valid.parquet')
P0 = [f'i0_p{k}' for k in range(22)]
t = pf.read_row_group(0, columns=P0+['i0_dp0','i0_dp1','a0','a2','a3','a5','a6','a7','t0','t1','is_scored']).to_pandas()
fig, ax = plt.subplots(6,1, figsize=(16,16), sharex=True)
for c in ['i0_p0','i0_p3','i0_p8','i0_p11','i0_p13']: ax[0].plot(t[c].values, lw=.5, label=c)
ax[0].legend(); ax[0].set_title('i0 price-like features, valid seq 0')
ax[1].plot(t.t0.values, lw=.5, label='t0'); ax[1].plot(t.t1.values, lw=.5, label='t1'); ax[1].legend()
ax[2].plot(np.cumsum(np.r_[0,np.diff(t.t0.values)]), lw=.5, label='cum dt0'); ax[2].legend()
for c in ['a2','a3','a5']: ax[3].plot(t[c].values, lw=.5, label=c)
ax[3].legend()
for c in ['a6','a7']: ax[4].plot(np.maximum(t[c].values,-3), lw=.5, label=c)
ax[4].legend(); ax[5].plot(t.a0.values, lw=.3, label='a0'); ax[5].legend()
plt.tight_layout(); plt.savefig('research/campaign_2026-10-03/eda/fractal/raw_seq0.png', dpi=70)
fig, ax = plt.subplots(3,1, figsize=(16,10), sharex=True)
s=slice(5000,5600)
for c in ['i0_p0','i0_p3','i0_p8','i0_p13']: ax[0].plot(np.arange(20000)[s], t[c].values[s], lw=.8, label=c, drawstyle='steps-post')
ax[0].legend()
ax[1].plot(np.arange(20000)[s], t.t0.values[s], drawstyle='steps-post', label='t0'); ax[1].plot(np.arange(20000)[s], t.t1.values[s], drawstyle='steps-post', label='t1'); ax[1].legend()
ax[2].plot(np.arange(20000)[s], t.i0_dp0.values[s], drawstyle='steps-post', label='dp0'); ax[2].plot(np.arange(20000)[s], t.a2.values[s], label='a2'); ax[2].legend()
plt.tight_layout(); plt.savefig('research/campaign_2026-10-03/eda/fractal/raw_seq0_zoom.png', dpi=70)
