HERE = Path(__file__).resolve().parent


def sha(path: Path) -> str:
    """Stream small local evidence, without loading any capture/data."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(65536):
            digest.update(block)
    return digest.hexdigest()


def save(name: str, value: object) -> None:
    """Save rational quantities as exact strings, retaining floating diagnostics."""
    (HERE / name).write_text(json.dumps(value, indent=2, default=str) + "\n")


def experiment() -> dict[str, object]:
    """Exhaustively compare compensated credit with an independent forward oracle."""
    cases = {}
    scalar = graph(((Q(1),),), (Q(0),), (Q(1),), ((Q(0),),) * 2, ((Q(0),), (Q(1),)))
    if forward_oracle(scalar) != (Q(2), Q(2)):
        raise AssertionError("closed-form two-step gradient failed")
    cases["scalar_two_step"] = analyze(scalar, (Q(1, 2),), True)
    vector_witness = graph(((Q(1),),), (Q(1),), (Q(0),), ((Q(0),),) * 2, ((Q(0),), (Q(1),)))
    if forward_oracle(vector_witness) != (Q(1), Q(2)):
        raise AssertionError("closed-form vector-parameter witness failed")
    for value, expected in (
        (scalar, ((Q(1), Q(1)), (Q(3), Q(3)))),
        (vector_witness, ((Q(1), Q(1)), (Q(1), Q(3)))),
    ):
        for kept, gradient in zip((False, True), expected, strict=True):
            if reverse_credit(value, (kept,), (Q(1, 2),), True)[0] != gradient:
                raise AssertionError("update witness not generated by recurrent graph")
    long = graph(((Q(1),),), (Q(0),), (Q(1),), ((Q(0),),) * 11, ((Q(0),),) * 10 + ((Q(1),),))
    if forward_oracle(long) != (Q(11), Q(11)):
        raise AssertionError("closed-form eleven-step gradient failed")
    for p in (Q(1, 4), Q(1, 2), Q(3, 4)):
        result = analyze(long, (p,) * 10, True)
        analytic_variance = sum(p ** (-min(i, j)) - 1 for i in range(11) for j in range(11))
        if result["coordinate_variance"] != (analytic_variance, analytic_variance):
            raise AssertionError("independent shared-prefix covariance formula failed")
        expected_local = sum(p**k for k in range(11))
        if result["expected_active_local_vjps"] != expected_local:
            raise AssertionError("terminal credit-depth cost proxy failed")
        result["closed_form_coordinate_variance"] = analytic_variance
        cases["long_chain_p" + str(p)] = result
    vector = graph(
        ((Q(1, 2), Q(1, 4)), (Q(1, 8), Q(3, 4))),
        (Q(1, 8), Q(-1, 8)),
        (Q(1), Q(1, 2)),
        ((Q(0), Q(1, 4)), (Q(1, 8), Q(0)), (Q(-1, 4), Q(1, 8)), (Q(0), Q(0))),
        ((Q(1, 2), Q(0)), (Q(0), Q(1, 4)), (Q(1, 4), Q(1, 2)), (Q(1), Q(1, 2))),
    )
    cases["vector_shared_matrix_nonuniform"] = analyze(vector, (Q(1, 2), Q(3, 4), Q(1, 4)), True)
    polynomial = graph(
        ((Q(1, 4),),),
        (Q(1, 8),),
        (Q(1, 2),),
        ((Q(0),), (Q(1, 8),), (Q(-1, 16),), (Q(0),)),
        ((Q(1, 4),), (Q(0),), (Q(1, 2),), (Q(1),)),
        square=True,
    )
    cases["polynomial_fixed_graph"] = analyze(polynomial, (Q(1, 2), Q(3, 4), Q(1, 2)), True)
    null = graph(((Q(1),),), (Q(0),), (Q(1),), ((Q(0),),) * 3, ((Q(1),), (Q(0),), (Q(0),)))
    cases["first_loss_only_null"] = analyze(null, (Q(1, 2),) * 2, False)
    failure = graph(((Q(1),),), (Q(0),), (Q(1),), ((Q(0),),) * 3, ((Q(0),), (Q(0),), (Q(1),)))
    correlated = tuple(
        (reverse_credit(failure, (kept, kept), (Q(1, 2),) * 2, True)[0], Q(1, 2))
        for kept in (False, True)
    )
    wrong_mean = expectation(correlated)
    correct = forward_oracle(failure)
    if correct != (Q(3), Q(3)) or wrong_mean != (Q(4), Q(4)):
        raise AssertionError("planted correlated-edge assumption failure was not detected")
    return {
        "cases": cases,
        "update_witnesses": update_witnesses(),
        "correlated_edge_failure_control": {
            "oracle": correct,
            "inverse_marginal_compensated_mean": wrong_mean,
            "joint_two_edge_survival": Q(1, 2),
            "incorrect_product_of_marginals": Q(1, 4),
            "expected_failure_detected": True,
        },
        "enumeration_not_Monte_Carlo": True,
        "random_draws": 0,
        "scientific_gradient_threshold": "exact rational equality; additional fixed machine rounding only",
    }


def main() -> None:
    """Bind prereg/source before running, preserve failures and freeze all evidence."""
    if (HERE / "results.json").exists():
        raise FileExistsError("preserve frozen results; reproduce in a new authorized copy")
    inputs = [
        HERE / "PREREG.md",
        HERE / "credit_oracle.py",
        HERE / "run_probe.py",
        HERE.parent / "MEMORY_LITERATURE_ADDENDUM.md",
    ]
    bindings = {str(path): sha(path) for path in inputs}
    save("pre_experiment_bindings.json", bindings)
    save(
        "STATE.json",
        {
            "phase": "EXECUTING_PREREGISTERED_FINITE_GRAPH",
            "bindings": bindings,
            "GPU_launches": 0,
            "actual_data_reads": 0,
            "last_failure": None,
        },
    )
    started = time.perf_counter()
    try:
        result = experiment()
    except BaseException:
        (HERE / "failure.log").write_text(traceback.format_exc())
        save(
            "STATE.json",
            {"phase": "FAILED_RETAINED_NO_THRESHOLD_CHANGE", "last_failure": "failure.log"},
        )
        raise
    result["wall_seconds"] = time.perf_counter() - started
    result["peak_rss_kib"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if bindings != {str(path): sha(path) for path in inputs}:
        raise ValueError("preregistered inputs changed during computation")
    save("results.json", result)
    save(
        "STATE.json",
        {
            "phase": "FROZEN_FINITE_GRAPH_ORACLE_PASS_NO_TRAINING_APPROVAL",
            "requested_model": "gpt6.1-sol medium",
            "enumerated_case_count": len(result["cases"]),
            "max_masks_per_distribution": 1024,
            "exact_unbiased_gradient_checks_pass": True,
            "ordinary_bias_and_null_checks_pass": True,
            "independent_variance_formula_pass": True,
            "scalar_vector_clipping_and_Adam_like_counterexamples_pass": True,
            "correlated_edge_planted_failure_detected": True,
            "prereg_hash": bindings[str(HERE / "PREREG.md")],
            "inputs_unchanged": True,
            "wall_seconds": result["wall_seconds"],
            "peak_rss_kib": result["peak_rss_kib"],
            "random_draws": 0,
            "GPU_launches": 0,
            "fit_launches": 0,
            "actual_data_or_capture_reads": 0,
            "trainer_edits": False,
            "prior_evidence_edits": False,
            "full_paper_read": False,
            "ARTBP_exact_paper_implementation_claim": False,
            "actual_optimizer_update_unbiasedness_claim": False,
            "scientific_training_approval": False,
            "pending": [
                "independent review of finite-graph instrument",
                "no real-training/AMP/Muon proposal admitted by this toy",
            ],
            "last_failure": None,
        },
    )
    report = (HERE / "REPORT_TEMPLATE.md").read_text()
    report += "\nMeasured enumeration summary:\n\n| Case | Masks | Ordinary mean | Full gradient | Variance trace |\n|---|---:|---|---|---:|\n"
    for name, case in result["cases"].items():
        report += f"| {name} | {case['masks_enumerated']} | {case['ordinary_mean']} | {case['oracle']} | {float(case['variance_trace']):.9g} |\n"
    report += f"\nBody wall {result['wall_seconds']:.6f}s; peakRSS {result['peak_rss_kib']}KiB. Exact rational identities passed in every case; float diagnostics and fixed bounds are retained in results.json. No fixture/tolerance changes or failed execution.\n"
    (HERE / "REPORT.md").write_text(report)
    save(
        "HASHES.json",
        {
            "algorithm": "sha256",
            "manifest_self_excluded": True,
            "artifacts": {
                path.name: sha(path)
                for path in HERE.iterdir()
                if path.is_file() and path.name != "HASHES.json"
            },
            "external_input_bindings": {str(inputs[-1]): bindings[str(inputs[-1])]},
            "all_originals_unmodified": True,
        },
    )
    print(
        json.dumps(
            {
                "cases": len(result["cases"]),
                "wall_seconds": result["wall_seconds"],
                "peak_rss_kib": result["peak_rss_kib"],
                "exact_oracle_pass": True,
                "nonlinear_update_counterexamples": True,
                "GPU_launches": 0,
            }
        )
    )


if __name__ == "__main__":
    main()
