def _validate_registered_observations(
    report_data: object, binding_data: dict[str, Any]
) -> dict[str, Any]:
    keys = {
        "admission",
        "portable_manifest",
        "registered_source_identities",
        "observed_before_split",
        "observed_after_split",
        "observed_before_scoring",
        "observed_after_scoring",
    }
    data = _require_keys(report_data, keys, "registered_data")
    for name in ("admission", "portable_manifest", "registered_source_identities"):
        if not _strict_equal(
            data[name],
            binding_data["source_identities"]
            if name == "registered_source_identities"
            else binding_data[name],
        ):
            _fail(f"score result registered-data {name} differs from frozen binding")
    identities = binding_data["source_identities"]
    obs_names = (
        "observed_before_split",
        "observed_after_split",
        "observed_before_scoring",
        "observed_after_scoring",
    )
    snapshots = [_require_keys(data[name], set(identities), name) for name in obs_names]
    for relative, identity in identities.items():
        expected_keys = {
            "path",
            "resolved",
            "bytes",
            "device",
            "inode",
            "islink",
            "mtime_ns",
        }
        if not isinstance(identity, dict) or not expected_keys.issubset(identity):
            _fail(f"frozen registered source identity is malformed: {relative}")
        lexical_parent = str(PurePosixPath(identity["path"]).parent)
        observed_reference: dict[str, Any] | None = None
        parent_reference: dict[str, Any] | None = None
        for snapshot in snapshots:
            observation = _require_keys(
                snapshot[relative],
                {"path", "resolved", "bytes", "device", "inode", "islink", "mtime_ns", "parent"},
                f"registered source observation {relative}",
            )
            expected_stat = {
                key: identity[key]
                for key in ("path", "resolved", "bytes", "device", "inode", "islink", "mtime_ns")
            }
            if not _strict_equal({key: observation[key] for key in expected_stat}, expected_stat):
                _fail(
                    f"registered source observation differs from its accepted identity: {relative}"
                )
            _strict_int(observation["bytes"], f"{relative}.bytes", 1)
            _strict_int(observation["device"], f"{relative}.device")
            _strict_int(observation["inode"], f"{relative}.inode", 1)
            _strict_int(observation["mtime_ns"], f"{relative}.mtime_ns")
            if type(observation["islink"]) is not bool:
                _fail(f"registered source observation islink is malformed: {relative}")
            parent = _require_keys(
                observation["parent"], {"path", "resolved", "device", "inode"}, f"{relative}.parent"
            )
            resolved_parent_value = parent.get("resolved")
            if parent.get("path") != lexical_parent:
                _fail(
                    f"registered source parent path differs from its lexical leaf parent: {relative}"
                )
            if (
                not isinstance(resolved_parent_value, str)
                or not resolved_parent_value
                or not PurePosixPath(resolved_parent_value).is_absolute()
                or str(PurePosixPath(resolved_parent_value)) != resolved_parent_value
                or resolved_parent_value.startswith("//")
                or resolved_parent_value == "/"
                or any(part in {".", ".."} for part in PurePosixPath(resolved_parent_value).parts)
            ):
                _fail(
                    f"registered source parent resolution is not a normalized absolute path: {relative}"
                )
            _strict_int(parent.get("device"), f"{relative}.parent.device")
            _strict_int(parent.get("inode"), f"{relative}.parent.inode", 1)
            if observed_reference is not None and not _strict_equal(
                observation, observed_reference
            ):
                _fail(f"registered source observations changed across scorer phases: {relative}")
            observed_reference = observation
            if parent_reference is not None and not _strict_equal(parent, parent_reference):
                _fail(f"registered source parent changed across scorer phases: {relative}")
            parent_reference = parent
    return data


def _validate_score_values(report: dict[str, Any]) -> dict[str, Any]:
    expected_top = {
        "schema",
        "status",
        "created_utc",
        "scope",
        "source_commit",
        "source_manifest_sha256",
        "source_set_sha256",
        "split_manifest_sha256",
        "ordered_membership_sha256",
        "fixed_models",
        "export_manifest",
        "exported_file_pins",
        "registered_data",
        "scoring",
        "limitations",
    }
    if set(report) != expected_top:
        _fail("score result top-level fields differ from the frozen scorer V5 contract")
    if report.get("schema") != RESULT_SCHEMA or report.get("status") != RESULT_STATUS:
        _fail("score result schema/status differs")
    _timestamp(report.get("created_utc"), "score result created_utc")
    if report.get("scope") != SCORE_SCOPE or report.get("limitations") != LIMITATIONS:
        _fail("score result scope or exposure limitations differ")
    if (
        report.get("source_commit") != SOURCE_COMMIT
        or report.get("source_manifest_sha256") != SOURCE_MANIFEST_SHA256
        or report.get("source_set_sha256") != SOURCE_SET_SHA256
        or report.get("split_manifest_sha256") != SPLIT_SHA256
        or not _is_hex(report.get("ordered_membership_sha256"), 64)
    ):
        _fail("score result source/split identity differs")
    return report


def _validate_scoring(scoring: object) -> dict[str, Any]:
    keys = {
        "metric_id",
        "ordered_group_count",
        "distinct_component_count",
        "official_mask",
        "arms",
        "paired_contrasts_vs_control",
        "uncertainty_scope",
        "bootstrap",
    }
    result = _require_keys(scoring, keys, "scoring")
    if (
        result.get("metric_id") != METRIC_ID
        or result.get("official_mask") != "is_scored AND (t >= 99)"
        or result.get("uncertainty_scope")
        != "paired feature-only successor-component bootstrap conditional on these five fixed epoch-5 models; not fit-seed or public-transfer uncertainty"
        or _strict_int(result.get("ordered_group_count"), "ordered_group_count", 1) != N_GROUPS
    ):
        _fail("score metric, mask, exposure count, or uncertainty scope differs")
    distinct_components = _strict_int(
        result.get("distinct_component_count"), "distinct_component_count", 1
    )
    if distinct_components > N_GROUPS:
        _fail("distinct component count exceeds the fixed group count")
    arms = _require_keys(result.get("arms"), set(ARM_MODES), "scoring.arms")
    selected_rows: int | None = None
    for arm_name in ARM_MODES:
        score = _require_keys(
            arms[arm_name],
            {"t0", "t1", "wp", "selected_rows", "metric_id"},
            f"arm score {arm_name}",
        )
        if score.get("metric_id") != METRIC_ID:
            _fail(f"arm metric ID differs: {arm_name}")
        for name in ("t0", "t1", "wp"):
            value = _finite_number(score.get(name), f"{arm_name}.{name}")
            if not -1.0 <= value <= 1.0:
                _fail(f"{arm_name}.{name} is outside a correlation score range")
        count = _strict_int(score.get("selected_rows"), f"{arm_name}.selected_rows", 1)
        if count > N_GROUPS * (N_ROWS - WARMUP):
            _fail(f"{arm_name}.selected_rows exceeds the fixed scoring bound")
        if selected_rows is not None and count != selected_rows:
            _fail("the five arms do not share one scored target mask")
        selected_rows = count

    contrasts = _require_keys(
        result.get("paired_contrasts_vs_control"), set(CONTRAST_ARMS), "paired contrasts"
    )
    for arm_name in CONTRAST_ARMS:
        contrast = _require_keys(
            contrasts[arm_name], {"candidate_minus_control"}, f"contrast {arm_name}"
        )
        bootstrap = _require_keys(
            contrast["candidate_minus_control"],
            {
                "candidate_wp",
                "reference_wp",
                "mean_diff",
                "bootstrap_sd",
                "ci95",
                "p_le_0",
                "n_sequences",
                "n_components",
                "n_boot",
                "seed",
                "metric_id",
                "centered_moments",
            },
            f"bootstrap result {arm_name}",
        )
        if bootstrap.get("metric_id") != METRIC_ID or bootstrap.get("centered_moments") is not True:
            _fail(f"bootstrap metric or centered-moment mode differs: {arm_name}")
        if (
            _strict_int(bootstrap.get("n_sequences"), f"{arm_name}.n_sequences", 1) != N_GROUPS
            or _strict_int(bootstrap.get("n_components"), f"{arm_name}.n_components", 1)
            != distinct_components
            or _strict_int(bootstrap.get("n_boot"), f"{arm_name}.n_boot", 1) != BOOTSTRAP_REPLICATES
            or _strict_int(bootstrap.get("seed"), f"{arm_name}.seed") != BOOTSTRAP_SEED
        ):
            _fail(f"bootstrap sample or seed metadata differs: {arm_name}")
        numeric: dict[str, int | float] = {}
        for name in ("candidate_wp", "reference_wp", "mean_diff", "bootstrap_sd", "p_le_0"):
            numeric[name] = _finite_number(bootstrap.get(name), f"{arm_name}.{name}")
        if not -1 <= numeric["candidate_wp"] <= 1 or not -1 <= numeric["reference_wp"] <= 1:
            _fail(f"paired bootstrap scores are out of range: {arm_name}")
        if not math.isclose(
            numeric["candidate_wp"], arms[arm_name]["wp"], rel_tol=1e-12, abs_tol=1e-12
        ) or not math.isclose(
            numeric["reference_wp"], arms["control"]["wp"], rel_tol=1e-12, abs_tol=1e-12
        ):
            _fail(f"paired bootstrap scores do not join the pooled arm table: {arm_name}")
        if not math.isclose(
            numeric["mean_diff"],
            numeric["candidate_wp"] - numeric["reference_wp"],
            rel_tol=1e-12,
            abs_tol=1e-12,
        ):
            _fail(f"paired bootstrap mean difference does not join its scores: {arm_name}")
        if numeric["bootstrap_sd"] < 0 or not 0 <= numeric["p_le_0"] <= 1:
            _fail(f"paired bootstrap spread or probability is out of range: {arm_name}")
        ci95 = bootstrap.get("ci95")
        if not isinstance(ci95, list) or len(ci95) != 2:
            _fail(f"paired bootstrap CI must contain two endpoints: {arm_name}")
        low = _finite_number(ci95[0], f"{arm_name}.ci95[0]")
        high = _finite_number(ci95[1], f"{arm_name}.ci95[1]")
        if not -2 <= low <= high <= 2:
            _fail(f"paired bootstrap CI is out of order or range: {arm_name}")
    bootstrap_settings = _require_keys(
        result.get("bootstrap"), {"replicates", "seed", "centered_moments"}, "bootstrap settings"
    )
    if not _strict_equal(
        bootstrap_settings,
        {"replicates": BOOTSTRAP_REPLICATES, "seed": BOOTSTRAP_SEED, "centered_moments": True},
    ):
        _fail("score bootstrap settings differ from the fixed source protocol")
    return result


def build_root_acceptance(
    *,
    result_raw: bytes,
    capture_raw: bytes,
    score_admission_raw: bytes,
    score_launch_raw: bytes,
    export_acceptance_raw: bytes,
    export_exact_stop_raw: bytes,
    export_binding_raw: bytes,
    export_manifest_raw: bytes,
    result_path: str = RESULT_PATH,
) -> dict[str, Any]:
    """Validate exact result/capture/receipt joins and return a compact ROOT receipt."""
    if result_path != RESULT_PATH:
        _fail("score result path differs from the fixed export evidence root")
    if len(result_raw) > MAX_RESULT_BYTES:
        _fail("score RESULT.json exceeds the reviewed 1 MB metadata bound")
    report = _validate_score_values(_json_object(result_raw, "score RESULT.json", MAX_RESULT_BYTES))
    export_acceptance, binding, manifest = _validate_export_authority(
        export_acceptance_raw,
        export_exact_stop_raw,
        export_binding_raw,
        export_manifest_raw,
    )
    capture, invocation = _validate_native_capture(
        capture_raw, result_raw, score_admission_raw, score_launch_raw
    )
    _validate_score_receipts(
        score_admission_raw,
        score_launch_raw,
        invocation,
        export_acceptance_raw,
        export_exact_stop_raw,
    )

    source = binding["source"]
    split = binding["split"]
    if (
        report.get("source_commit") != source["commit"]
        or report.get("source_manifest_sha256") != source["manifest_sha256"]
        or report.get("source_set_sha256") != source["source_set_sha256"]
        or report.get("split_manifest_sha256") != split["sha256"]
        or report.get("ordered_membership_sha256") != export_acceptance["membership_sha256"]
    ):
        _fail("score report source or ordered membership differs from accepted inputs")
    expected_manifest_pin = {
        "path": str(PurePosixPath(binding["output_dir"]) / "EXPORT_MANIFEST_V1.json"),
        "bytes": len(export_manifest_raw),
        "sha256": _sha256(export_manifest_raw),
    }
    if not _strict_equal(report.get("export_manifest"), expected_manifest_pin):
        _fail("score report export-manifest pin differs from the accepted metadata bytes")
    if not _strict_equal(report.get("fixed_models"), _expected_fixed_models(binding)):
        _fail("score report five fixed model/receipt identities differ from the binding")
    expected_files = _expected_file_pins(binding, manifest)
    if not _strict_equal(report.get("exported_file_pins"), expected_files):
        _fail("score report's five prediction/sidecar pins differ from the accepted manifest")
    validated_data = _validate_registered_observations(
        report.get("registered_data"), binding["registered_data"]
    )
    if not _strict_equal(
        validated_data["observed_before_split"], validated_data["observed_after_split"]
    ):
        _fail("registered data changed during split validation")
    if not _strict_equal(
        validated_data["observed_after_split"], validated_data["observed_before_scoring"]
    ):
        _fail("registered data changed before scoring")
    if not _strict_equal(
        validated_data["observed_before_scoring"], validated_data["observed_after_scoring"]
    ):
        _fail("registered data changed during scoring")
    scoring = _validate_scoring(report.get("scoring"))
    _timestamp(capture["captured_utc"], "score capture timestamp")

    native_terminal = {
        "active_state": "active",
        "sub_state": "exited",
        "main_pid": 0,
        "exec_main_code": 1,
        "exec_main_status": 0,
    }
    source_record = {
        "source_commit": report["source_commit"],
        "source_manifest_sha256": report["source_manifest_sha256"],
        "source_set_sha256": report["source_set_sha256"],
        "split_manifest_sha256": report["split_manifest_sha256"],
        "ordered_membership_sha256": report["ordered_membership_sha256"],
        "export_manifest": report["export_manifest"],
        "fixed_models": report["fixed_models"],
        "exported_file_pins": report["exported_file_pins"],
        "registered_data": {
            "admission": validated_data["admission"],
            "portable_manifest": validated_data["portable_manifest"],
            "registered_source_identities": validated_data["registered_source_identities"],
        },
    }
    exposure = {
        "description": EXPOSURE_DESCRIPTION,
        "scope": report["scope"],
        "ordered_group_count": N_GROUPS,
        "ordered_membership_sha256": report["ordered_membership_sha256"],
        "pristine_or_public_holdout": False,
        "limitations": report["limitations"],
    }
    scalar_tables = {
        "metric_id": scoring["metric_id"],
        "official_mask": scoring["official_mask"],
        "ordered_group_count": scoring["ordered_group_count"],
        "distinct_component_count": scoring["distinct_component_count"],
        "arms": scoring["arms"],
        "paired_contrasts_vs_control": scoring["paired_contrasts_vs_control"],
        "uncertainty_scope": scoring["uncertainty_scope"],
        "bootstrap": scoring["bootstrap"],
    }
    return {
        "schema": ACCEPTANCE_SCHEMA,
        "status": ACCEPTANCE_STATUS,
        "created_utc": dt.datetime.now(dt.UTC).isoformat(),
        "unit": SCORE_UNIT,
        "invocation_id": invocation,
        "native_terminal": native_terminal,
        "result": {
            "path": result_path,
            "bytes": len(result_raw),
            "sha256": _sha256(result_raw),
            "schema": report["schema"],
            "status": report["status"],
        },
        "score_receipts": {
            "admission": _receipt_pin(score_admission_raw),
            "launch": _receipt_pin(score_launch_raw),
            "export_acceptance": _receipt_pin(export_acceptance_raw),
            "export_exact_stop": _receipt_pin(export_exact_stop_raw),
            "status_capture": {"bytes": len(capture_raw), "sha256": _sha256(capture_raw)},
            "export_manifest": _receipt_pin(export_manifest_raw),
        },
        "source": source_record,
        "exposure": exposure,
        "scalar_tables": scalar_tables,
        "stop_status": "PENDING_EXACT_STOP",
        "score_gain_or_public_transfer_claim": False,
    }


def write_root_acceptance_exclusive(path: Path, receipt: dict[str, Any]) -> bytes:
    """Create the compact acceptance once, fsyncing the new file and its directory."""
    if not isinstance(path, Path) or not path.is_absolute():
        _fail("acceptance output path must be an absolute pathlib.Path")
    parent = path.parent
    parent_stat = parent.lstat()
    if not stat.S_ISDIR(parent_stat.st_mode):
        _fail("acceptance output parent is not a real directory")
    if (
        receipt.get("schema") != ACCEPTANCE_SCHEMA
        or receipt.get("status") != ACCEPTANCE_STATUS
        or receipt.get("unit") != SCORE_UNIT
        or receipt.get("stop_status") != "PENDING_EXACT_STOP"
    ):
        _fail("acceptance output does not match this validator's receipt contract")
    raw = (json.dumps(receipt, ensure_ascii=False, allow_nan=False, indent=2) + "\n").encode(
        "utf-8"
    )
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(path, flags, 0o600)
    with os.fdopen(descriptor, "wb") as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())
    parent_descriptor = os.open(
        parent,
        os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0),
    )
    try:
        os.fsync(parent_descriptor)
    finally:
        os.close(parent_descriptor)
    return raw
