def _membership_sha256(groups: list[int]) -> str:
    encoded = "".join(f"{group}\n" for group in groups).encode("ascii")
    return _sha256(encoded)


def _validate_native_capture(
    capture_raw: bytes,
    result_raw: bytes,
    admission_raw: bytes,
    launch_raw: bytes,
) -> tuple[dict[str, Any], str]:
    capture = _json_object(capture_raw, "score status capture", MAX_CAPTURE_BYTES)
    expected_capture_fields = {
        "schema",
        "captured_utc",
        "unit_name",
        "invocation_id",
        "terminal_success",
        "unit",
        "parent",
        "parent_events",
        "own_cgroup_files",
        "parent_populated_files",
        "selected_gpu",
        "files",
        "result_capture",
        "code_pins",
        "scope",
    }
    if set(capture) != expected_capture_fields:
        _fail("score status capture top-level fields differ from reviewed V4")
    _timestamp(capture.get("captured_utc"), "score capture captured_utc")
    invocation = capture.get("invocation_id")
    if (
        capture.get("schema") != "fg19.first-cell-score-bounded-status.v1"
        or capture.get("unit_name") != SCORE_UNIT
        or not _is_hex(invocation, 32)
        or capture.get("terminal_success") is not True
    ):
        _fail("score status capture does not identify one strict successful invocation")
    unit = capture.get("unit")
    if not isinstance(unit, dict) or any(not isinstance(value, str) for value in unit.values()):
        _fail("captured score unit properties are malformed")
    if (
        unit.get("Id") != SCORE_UNIT
        or unit.get("InvocationID") != invocation
        or unit.get("ActiveState") != "active"
        or unit.get("SubState") != "exited"
        or unit.get("MainPID") != "0"
        or unit.get("ExecMainCode") != "1"
        or unit.get("ExecMainStatus") != "0"
        or unit.get("Result") != "success"
    ):
        _fail("captured score unit lacks the strict successful 0-1-0 terminal tuple")
    files = capture.get("files")
    if not isinstance(files, dict) or set(files) != {
        "ADMISSION.json",
        "LAUNCH.json",
        "unit.log",
        "RESULT.json",
    }:
        _fail("successful score capture lacks exactly its bounded receipts, log, and result")
    if (
        _b64_bytes(files["ADMISSION.json"], "captured ADMISSION.json", cap=MAX_RECEIPT_BYTES)
        != admission_raw
    ):
        _fail("captured score admission does not join the supplied raw receipt")
    if (
        _b64_bytes(files["LAUNCH.json"], "captured LAUNCH.json", cap=MAX_RECEIPT_BYTES)
        != launch_raw
    ):
        _fail("captured score launch does not join the supplied raw receipt")
    result_record = files["RESULT.json"]
    if (
        not isinstance(result_record, dict)
        or set(result_record)
        != {
            "read",
            "bytes",
            "sha256",
            "base64",
        }
        or result_record.get("read") is not True
    ):
        _fail("captured RESULT.json record is malformed")
    embedded_result = _b64_bytes(
        {key: result_record[key] for key in ("bytes", "sha256", "base64")},
        "captured RESULT.json",
        cap=MAX_RESULT_BYTES,
    )
    if embedded_result != result_raw:
        _fail("supplied RESULT.json bytes differ from the exact native capture")
    result_capture = _require_keys(
        capture.get("result_capture"), {"read", "bytes", "sha256"}, "result_capture"
    )
    if result_capture.get("read") is not True or (
        result_capture.get("bytes"),
        result_capture.get("sha256"),
    ) != (len(result_raw), _sha256(result_raw)):
        _fail("score capture summary does not join exact RESULT.json bytes")

    log_record = _require_keys(
        files["unit.log"],
        {"bytes", "captured_bytes", "tail_offset_bytes", "tail_sha256", "tail_base64"},
        "unit.log capture",
    )
    log_bytes = _strict_int(log_record.get("bytes"), "unit.log.bytes")
    captured_bytes = _strict_int(log_record.get("captured_bytes"), "unit.log.captured_bytes")
    tail_offset = _strict_int(log_record.get("tail_offset_bytes"), "unit.log.tail_offset_bytes")
    if captured_bytes > MAX_LOG_TAIL_BYTES or log_bytes - captured_bytes != tail_offset:
        _fail("score unit log tail length or offset exceeds the reviewed bound")
    try:
        tail = base64.b64decode(log_record.get("tail_base64", ""), validate=True)
    except (ValueError, base64.binascii.Error) as error:
        raise ValueError("score unit log tail base64 is invalid") from error
    if (
        len(tail) != captured_bytes
        or base64.b64encode(tail).decode("ascii") != log_record.get("tail_base64")
        or not _is_hex(log_record.get("tail_sha256"), 64)
        or _sha256(tail) != log_record.get("tail_sha256")
    ):
        _fail("score unit log tail bytes or digest differ")

    code_pins = capture.get("code_pins")
    if not isinstance(code_pins, dict) or set(code_pins) != set(EXPECTED_SCORE_CODE_PINS):
        _fail("captured scorer code pin inventory differs")
    for name, (byte_count, digest) in EXPECTED_SCORE_CODE_PINS.items():
        pin = code_pins[name]
        if not _strict_equal(pin, {"bytes": byte_count, "sha256": digest}):
            _fail(f"captured scorer code pin differs: {name}")
    return capture, invocation


