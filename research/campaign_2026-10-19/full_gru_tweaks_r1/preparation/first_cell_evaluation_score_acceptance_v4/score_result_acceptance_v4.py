def _fail(message: str) -> None:
    raise ValueError(message)


def _sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _strict_equal(left: Any, right: Any) -> bool:
    """Compare JSON values without Python's bool/int equivalence."""
    if type(left) is not type(right):
        return False
    if isinstance(left, dict):
        return left.keys() == right.keys() and all(
            _strict_equal(left[key], right[key]) for key in left
        )
    if isinstance(left, list):
        return len(left) == len(right) and all(
            _strict_equal(a, b) for a, b in zip(left, right, strict=True)
        )
    return left == right


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            _fail(f"duplicate JSON object key: {key}")
        result[key] = value
    return result


def _reject_constant(value: str) -> None:
    _fail(f"nonstandard JSON number is forbidden: {value}")


def _json_object(raw: bytes, label: str, cap: int) -> dict[str, Any]:
    if type(raw) is not bytes or not raw or len(raw) > cap:
        _fail(f"{label} bytes are empty, not bytes, or exceed {cap}")
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_unique_object,
            parse_constant=_reject_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ValueError(f"{label} is not strict UTF-8 JSON") from error
    if not isinstance(value, dict):
        _fail(f"{label} must be a JSON object")
    return value


def _is_hex(value: object, length: int) -> bool:
    return (
        isinstance(value, str)
        and len(value) == length
        and all(character in "0123456789abcdef" for character in value)
    )


def _strict_int(value: object, label: str, minimum: int = 0) -> int:
    if type(value) is not int or value < minimum:
        _fail(f"{label} must be a strict integer >= {minimum}")
    return value


def _finite_number(value: object, label: str) -> int | float:
    if type(value) not in (int, float) or not math.isfinite(value):
        _fail(f"{label} must be a finite JSON number, excluding booleans")
    return value


def _timestamp(value: object, label: str) -> None:
    if not isinstance(value, str) or not value:
        _fail(f"{label} must be an ISO timestamp")
    try:
        parsed = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as error:
        raise ValueError(f"{label} must be an ISO timestamp") from error
    if parsed.tzinfo is None:
        _fail(f"{label} must include a timezone")


def _b64_bytes(record: object, label: str, *, cap: int) -> bytes:
    if not isinstance(record, dict) or set(record) != {"bytes", "sha256", "base64"}:
        _fail(f"{label} capture record has an unexpected shape")
    expected_bytes = _strict_int(record.get("bytes"), f"{label}.bytes", 1)
    digest = record.get("sha256")
    encoded = record.get("base64")
    if not _is_hex(digest, 64) or not isinstance(encoded, str):
        _fail(f"{label} capture record is missing a digest or base64")
    try:
        raw = base64.b64decode(encoded, validate=True)
    except (ValueError, base64.binascii.Error) as error:
        raise ValueError(f"{label} capture base64 is invalid") from error
    if len(raw) > cap or base64.b64encode(raw).decode("ascii") != encoded:
        _fail(f"{label} capture base64 is noncanonical or oversized")
    if (len(raw), _sha256(raw)) != (expected_bytes, digest):
        _fail(f"{label} capture byte count or SHA-256 differs")
    return raw


def _receipt_pin(raw: bytes) -> dict[str, Any]:
    return {"bytes": len(raw), "sha256": _sha256(raw)}


def _require_keys(value: object, keys: set[str], label: str) -> dict[str, Any]:
    if not isinstance(value, dict) or set(value) != keys:
        _fail(f"{label} key set differs")
    return value


