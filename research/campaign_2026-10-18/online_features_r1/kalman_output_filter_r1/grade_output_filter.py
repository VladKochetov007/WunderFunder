from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from types import ModuleType
from typing import cast

import numpy as np

ROOT = Path(__file__).resolve().parents[4]
PACKET = Path(__file__).resolve().parent
RECIPE_PATH = PACKET / "recipe.json"
SPLIT_REL = "research/campaign_2026-09-29/artifacts/splits/fold0.json"
TARGET_REL = "cache/valid_targets.npz"
ANCESTRY_REL = (
    "research/campaign_2026-10-18/online_features_r1/"
    "warmup_expert_gate_r1/preflight_r1.json"
)
FOLD_HELPER_REL = (
    "research/campaign_2026-10-18/online_features_r1/"
    "warmup_expert_gate_r1/grade_gate.py"
)


def sha256_file(path: Path) -> str:
    """Hash a file incrementally without loading it into memory."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_ints(values: list[int]) -> str:
    """Hash an ordered integer list using canonical compact JSON bytes."""
    payload = json.dumps(values, separators=(",", ":")).encode("ascii")
    return hashlib.sha256(payload).hexdigest()


def load_module(name: str, path: Path) -> ModuleType:
    """Load one repository helper by its source path."""
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load helper at {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_group_order(
    split: dict[str, object], groups: list[int], recipe: dict[str, object]
) -> tuple[list[int], list[int]]:
    """Bind sequence and component identifiers to the exact F0 group order."""
    rows = {int(row["row_group"]): row for row in split["sequences"]["valid"]}
    if any(group not in rows for group in groups):
        raise ValueError("split lacks a selected source-qualified F0 group")
    sequence_ids = [int(rows[group]["seq_ix"]) for group in groups]
    components = [int(rows[group]["component"]) for group in groups]
    expected = cast(dict[str, object], recipe["evaluation"])
    if (
        sha256_ints(groups) != expected["group_order_sha256"]
        or sha256_ints(sequence_ids) != expected["sequence_id_order_sha256"]
        or sha256_ints(components) != expected["component_order_sha256"]
    ):
        raise ValueError("F0 group, sequence, or component order differs from the recipe")
    return sequence_ids, components


def write_preflight(
    root: Path,
    recipe: dict[str, object],
    groups: list[int],
    sequence_ids: list[int],
    components: list[int],
    parent_path: Path,
    output_path: Path,
    output_receipt_path: Path,
    target_path: Path,
    preflight_path: Path,
) -> dict[str, object]:
    """Write an identity receipt before decoding or using numeric targets/masks."""
    split_sha = str(recipe["split_manifest_sha256"])
    endpoint = cast(dict[str, object], recipe["parent_endpoint"])
    prior_path = root / str(endpoint["fit_membership_preflight"])
    if sha256_file(parent_path) != endpoint["prediction_sha256"]:
        raise ValueError("parent prediction differs from the frozen recipe")
    if sha256_file(prior_path) != endpoint["fit_membership_preflight_sha256"]:
        raise ValueError("parent fit-membership preflight differs from the frozen recipe")
    prior = json.loads(prior_path.read_text(encoding="utf-8"))
    if prior.get("status") != "pass" or prior.get("split_manifest_sha256") != split_sha:
        raise ValueError("parent fit-membership preflight does not pass on this split")
    if prior.get("evaluation_group_order_sha256") != sha256_ints(groups):
        raise ValueError("parent fit-membership preflight names another F0 group order")

    generation = json.loads(output_receipt_path.read_text(encoding="utf-8"))
    if generation.get("status") != "complete" or generation.get("target_or_mask_numeric_values_read") is not False:
        raise ValueError("filter generation was not label-blind and complete")
    if generation.get("recipe_sha256") != sha256_file(RECIPE_PATH):
        raise ValueError("filter cache was generated from another recipe")
    if generation.get("generator_sha256") != sha256_file(PACKET / "generate_predictions.py"):
        raise ValueError("filter cache was generated by different source code")
    if generation.get("parent_endpoint", {}).get("prediction_sha256") != endpoint[
        "prediction_sha256"
    ]:
        raise ValueError("filter cache names another parent prediction endpoint")
    if generation.get("row_groups") != groups:
        raise ValueError("filter cache row groups differ from the F0 evaluation order")
    if generation.get("sequence_id_order_sha256") != sha256_ints(sequence_ids):
        raise ValueError("filter cache sequence IDs differ from the frozen split")
    if generation.get("component_order_sha256") != sha256_ints(components):
        raise ValueError("filter cache component IDs differ from the frozen split")

    cache = cast(dict[str, object], generation["prediction_output"])
    if Path(str(cache["path"])).resolve(strict=True) != output_path.resolve(strict=True):
        raise ValueError("filter receipt points to a different prediction file")
    if cache["sha256"] != sha256_file(output_path):
        raise ValueError("filter prediction bytes differ from their receipt")
    predictions = np.load(output_path, mmap_mode="r", allow_pickle=False)
    if predictions.shape != (2, len(groups), 20_000, 2) or predictions.dtype != np.float32:
        raise ValueError("filter predictions have an unexpected shape or precision")
    if not np.isfinite(predictions[:, :, 99:, :]).all():
        raise ValueError("filter predictions contain nonfinite scored outputs")

    target_path = root / TARGET_REL
    if sha256_file(target_path) != recipe["target_cache_sha256"]:
        raise ValueError("target cache differs from the frozen recipe")
    campaign = load_module(
        "kalman_output_filter_campaign_score",
        root / "research/campaign_2026-09-30/audit/campaign_score.py",
    )
    target_cache = cast(dict[str, np.memmap], campaign.mmap_stored_npz(target_path))
    cached_groups = [int(value) for value in target_cache["row_group"]]
    if cached_groups != list(range(1_873)):
        raise ValueError("target-cache row-group index differs from full validation order")
    if any(group not in set(cached_groups) for group in groups):
        raise ValueError("target cache lacks selected F0 groups")

    source_hashes = {
        "recipe": sha256_file(RECIPE_PATH),
        "prediction_generator": sha256_file(PACKET / "generate_predictions.py"),
        "prediction_grader": sha256_file(Path(__file__).resolve()),
        "prediction_receipt": sha256_file(output_receipt_path),
        "prior_fit_membership_preflight": sha256_file(prior_path),
        "prediction_aligner": sha256_file(root / "scripts/grade_prediction_bank.py"),
        "target_cache_reader": sha256_file(
            root / "research/campaign_2026-09-30/audit/campaign_score.py"
        ),
        "official_metric": sha256_file(root / "src/wnn/gmetric.py"),
        "component_evaluation": sha256_file(root / "src/wnn/evaluation.py"),
        "descriptive_fold_assigner": sha256_file(root / FOLD_HELPER_REL),
    }
    payload: dict[str, object] = {
        "schema": "wnn.kalman_output_filter.preflight.v1",
        "created_utc": datetime.now(UTC).isoformat(),
        "status": "pass",
        "target_numeric_values_decoded_or_used": False,
        "scoring_mask_values_decoded_or_used": False,
        "fold": 0,
        "split_manifest_sha256": split_sha,
        "evaluation_groups": len(groups),
        "evaluation_components": len(set(components)),
        "evaluation_group_order_sha256": sha256_ints(groups),
        "evaluation_sequence_id_order_sha256": sha256_ints(sequence_ids),
        "evaluation_component_order_sha256": sha256_ints(components),
        "parent_endpoint": {
            "prediction_sha256": endpoint["prediction_sha256"],
            "sidecar_sha256": endpoint["sidecar_sha256"],
            "checkpoint_sha256": endpoint["checkpoint_sha256"],
            "fit_membership_preflight_sha256": endpoint[
                "fit_membership_preflight_sha256"
            ],
        },
        "filter_predictions": {
            "path": str(output_path),
            "sha256": cache["sha256"],
            "receipt_path": str(output_receipt_path),
            "receipt_sha256": source_hashes["prediction_receipt"],
            "shape": list(predictions.shape),
            "dtype": str(predictions.dtype),
        },
        "target_cache": {
            "path": str(target_path.relative_to(root)),
            "size_bytes": target_path.stat().st_size,
            "sha256": recipe["target_cache_sha256"],
            "row_group_count": len(cached_groups),
        },
        "source_hashes": source_hashes,
        "descriptive_folds": {
            "assigner": FOLD_HELPER_REL,
            "seed": recipe["grading"]["descriptive_fold_partition_seed"],
            "count": recipe["grading"]["descriptive_fold_count"],
        },
    }
    fingerprint = hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    payload["fingerprint"] = fingerprint
    preflight_path.parent.mkdir(parents=True, exist_ok=True)
    with preflight_path.open("x", encoding="utf-8") as stream:
        json.dump(payload, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write("\n")
    return payload


def main_grade(
    root: Path,
    output_path: Path,
    output_receipt_path: Path,
    preflight_path: Path,
    result_path: Path,
) -> dict[str, object]:
    """Score frozen raw/fixed/adaptive predictions under the official metric."""
    root = root.resolve(strict=True)
    recipe = json.loads(RECIPE_PATH.read_text(encoding="utf-8"))
    split_path = root / SPLIT_REL
    if sha256_file(split_path) != recipe["split_manifest_sha256"]:
        raise ValueError("source-qualified split differs from the frozen recipe")
    split = json.loads(split_path.read_text(encoding="utf-8"))
    groups = [int(group) for group in split["evaluation"]["valid"]]
    sequence_ids, components = check_group_order(split, groups, recipe)
    fold_helper = load_module(
        "kalman_output_filter_fold_helper", root / FOLD_HELPER_REL
    )
    grading_spec = cast(dict[str, object], recipe["grading"])
    if (
        grading_spec["descriptive_fold_partition_seed"] != fold_helper.FOLD_SEED
        or grading_spec["descriptive_fold_count"] != fold_helper.N_FOLDS
    ):
        raise ValueError("descriptive fold helper differs from the frozen recipe")

    endpoint = cast(dict[str, object], recipe["parent_endpoint"])
    parent_path = root / str(endpoint["prediction"])
    if sha256_file(parent_path) != endpoint["prediction_sha256"]:
        raise ValueError("raw parent prediction bytes differ from the frozen recipe")
    sidecar_path = root / str(endpoint["sidecar"])
    if sha256_file(sidecar_path) != endpoint["sidecar_sha256"]:
        raise ValueError("raw parent sidecar differs from the frozen recipe")
    sidecar = json.loads(sidecar_path.read_text(encoding="utf-8"))
    if (
        sidecar.get("checkpoint_sha256") != endpoint["checkpoint_sha256"]
        or sidecar.get("split_manifest_sha256") != recipe["split_manifest_sha256"]
        or sidecar.get("row_groups") != list(range(1_873))
    ):
        raise ValueError("raw parent sidecar has different checkpoint, split, or group order")

    output_path = output_path.resolve(strict=True)
    output_receipt_path = output_receipt_path.resolve(strict=True)
    prior_preflight = root / str(endpoint["fit_membership_preflight"])
    if sha256_file(prior_preflight) != endpoint["fit_membership_preflight_sha256"]:
        raise ValueError("parent fit-membership preflight differs from the frozen recipe")
    prior = json.loads(prior_preflight.read_text(encoding="utf-8"))
    if (
        prior.get("status") != "pass"
        or prior.get("split_manifest_sha256") != recipe["split_manifest_sha256"]
        or prior.get("target_numeric_values_decoded_or_used") is not False
    ):
        raise ValueError("parent fit-membership preflight is invalid")

    sys.path.insert(0, str(root / "src"))
    grade = load_module(
        "kalman_output_filter_prediction_bank", root / "scripts/grade_prediction_bank.py"
    )
    aligned = grade.aligned({"prediction": str(endpoint["prediction"])}, groups, str(recipe["split_manifest_sha256"]))
    if isinstance(aligned, str):
        raise ValueError(f"raw parent prediction alignment failed: {aligned}")
    parent_array, parent_order = aligned
    if parent_array.dtype != np.float32 or parent_array.shape[1:] != (20_000, 2):
        raise ValueError("raw parent prediction shape or precision differs")
    parent_view = grade.Lazy(parent_array, parent_order)

    generation = json.loads(output_receipt_path.read_text(encoding="utf-8"))
    if generation.get("row_groups") != groups:
        raise ValueError("filter prediction receipt row groups differ from the frozen split")
    if generation.get("target_or_mask_numeric_values_read") is not False:
        raise ValueError("filter prediction generation read target or mask values")
    if generation.get("recipe_sha256") != sha256_file(RECIPE_PATH):
        raise ValueError("filter prediction generation used a different recipe")
    output_receipt = cast(dict[str, object], generation["prediction_output"])
    if output_receipt["sha256"] != sha256_file(output_path):
        raise ValueError("filter prediction bytes differ from their receipt")
    filters = np.load(output_path, mmap_mode="r", allow_pickle=False)
    if filters.shape != (2, len(groups), 20_000, 2) or filters.dtype != np.float32:
        raise ValueError("filter prediction cache has unexpected shape or precision")

    target_path = root / TARGET_REL
    preflight = write_preflight(
        root,
        recipe,
        groups,
        sequence_ids,
        components,
        parent_path,
        output_path,
        output_receipt_path,
        target_path,
        preflight_path,
    )
    campaign = load_module(
        "kalman_output_filter_campaign_score",
        root / "research/campaign_2026-09-30/audit/campaign_score.py",
    )
    target_cache = cast(dict[str, np.memmap], campaign.mmap_stored_npz(target_path))
    cached_groups = [int(value) for value in target_cache["row_group"]]
    if cached_groups != list(range(1_873)):
        raise ValueError("target-cache row-group index differs from full validation order")
    target_positions = {group: position for position, group in enumerate(cached_groups)}
    if any(group not in target_positions for group in groups):
        raise ValueError("target cache lacks selected F0 groups")

    from wnn.evaluation import paired_component_bootstrap, paired_component_moments
    from wnn.gmetric import GlobalAccumulator

    group_folds = fold_helper.grouped_folds(components)
    arm_names = ["raw_parent", "fixed_q_over_r_025", "prefix_moments_q_over_r"]
    pooled = {name: GlobalAccumulator() for name in arm_names}
    per_fold: list[dict[str, object]] = []
    moment_pairs = {
        name: [np.zeros((len(groups), 2, 6), dtype=np.float64), np.zeros((len(groups), 2, 6), dtype=np.float64)]
        for name in arm_names[1:]
    }

    for fold in range(int(grading_spec["descriptive_fold_count"])):
        indices = np.flatnonzero(group_folds == fold)
        fold_accumulators = {name: GlobalAccumulator() for name in arm_names}
        for index in indices:
            local_index = int(index)
            group = groups[local_index]
            cache_index = target_positions[group]
            target = np.asarray(target_cache["y"][cache_index], dtype=np.float32)
            selection = np.asarray(target_cache["mask"][cache_index], dtype=bool).copy()
            selection[:99] = False
            raw = parent_view[slice(local_index, local_index + 1)][0]
            candidates = [raw, filters[0, local_index], filters[1, local_index]]
            if not all(np.isfinite(prediction[99:]).all() for prediction in candidates):
                raise ValueError(f"nonfinite scored prediction for row group {group}")
            for name, prediction in zip(arm_names, candidates, strict=True):
                fold_accumulators[name].add(target[None], prediction[None], selection[None])
                pooled[name].add(target[None], prediction[None], selection[None])
            for name, prediction in zip(arm_names[1:], candidates[1:], strict=True):
                candidate_moments, reference_moments = paired_component_moments(
                    target[None], prediction[None], raw[None], selection[None]
                )
                moment_pairs[name][0][local_index] = candidate_moments[0]
                moment_pairs[name][1][local_index] = reference_moments[0]

        fold_scores = {
            name: float(accumulator.result()["wp"])
            for name, accumulator in fold_accumulators.items()
        }
        per_fold.append(
            {
                "fold": fold,
                "groups": int(len(indices)),
                "components": int(len(set(np.asarray(components)[indices].tolist()))),
                "scores_wp": fold_scores,
                "delta_vs_raw_wp": {
                    name: fold_scores[name] - fold_scores["raw_parent"]
                    for name in arm_names[1:]
                },
            }
        )

    bootstrap = {}
    for name, (candidate_moments, reference_moments) in moment_pairs.items():
        bootstrap[name] = paired_component_bootstrap(
            candidate_moments,
            reference_moments,
            np.asarray(components, dtype=np.int64),
            n_boot=int(recipe["grading"]["component_bootstrap_replicates"]),
            seed=int(recipe["grading"]["component_bootstrap_seed"]),
            centered=True,
        )

    result: dict[str, object] = {
        "schema": "wnn.kalman_output_filter.result.v1",
        "created_utc": datetime.now(UTC).isoformat(),
        "status": "complete",
        "hypothesis_id": recipe["hypothesis_id"],
        "experiment_id": recipe["experiment_id"],
        "recipe_sha256": sha256_file(RECIPE_PATH),
        "preflight_path": str(preflight_path),
        "preflight_sha256": sha256_file(preflight_path),
        "preflight_fingerprint": preflight["fingerprint"],
        "prediction_receipt_path": str(output_receipt_path),
        "prediction_receipt_sha256": sha256_file(output_receipt_path),
        "filter_prediction_sha256": sha256_file(output_path),
        "target_cache_sha256": recipe["target_cache_sha256"],
        "split_manifest_sha256": recipe["split_manifest_sha256"],
        "metric_id": recipe["metric_id"],
        "evaluation_groups": len(groups),
        "evaluation_components": len(set(components)),
        "scoring_rows": int(sum(int(acc.result()["selected_rows"]) for acc in pooled.values()) // len(pooled)),
        "exposure": recipe["evaluation"]["exposure"],
        "scores_wp": {
            name: float(accumulator.result()["wp"]) for name, accumulator in pooled.items()
        },
        "delta_vs_raw_wp": {
            name: float(pooled[name].result()["wp"] - pooled["raw_parent"].result()["wp"])
            for name in arm_names[1:]
        },
        "fold_results": per_fold,
        "paired_component_bootstrap_vs_raw": bootstrap,
        "filter_parameter_summary": summarize_parameters(generation["parameters_by_group"]),
        "limitations": [
            "All F0 endpoints and labels were previously exposed; these are fixed-prediction diagnostics, not clean-CV or public-transfer evidence.",
            "Component bootstrap conditions on one fitted parent checkpoint and does not estimate training-seed or unseen-regime uncertainty.",
            "The adaptive arm estimates Q/R from the model's own first-99 predictions; it does not use observed labels or demonstrate feedback-based learning.",
            "A positive postprocessing screen would need separate causal serving, reset, runtime and cross-fold checks before release.",
        ],
        "source_hashes": {
            "prediction_generator": generation["generator_sha256"],
            "prediction_grader": sha256_file(Path(__file__).resolve()),
            "official_metric": sha256_file(root / "src/wnn/gmetric.py"),
            "component_evaluation": sha256_file(root / "src/wnn/evaluation.py"),
            "descriptive_fold_assigner": sha256_file(root / FOLD_HELPER_REL),
        },
        "descriptive_folds": {
            "assigner": FOLD_HELPER_REL,
            "seed": grading_spec["descriptive_fold_partition_seed"],
            "count": grading_spec["descriptive_fold_count"],
        },
    }
    result_path.parent.mkdir(parents=True, exist_ok=True)
    with result_path.open("x", encoding="utf-8") as stream:
        json.dump(result, stream, indent=2, sort_keys=True, allow_nan=False)
        stream.write("\n")
    return result


def summarize_parameters(rows: list[dict[str, object]]) -> dict[str, object]:
    """Summarize the prefix-derived per-sequence filter parameters."""
    ratios = np.asarray(
        [channel["q_over_r"] for row in rows for channel in row["prefix_moment_channels"]],
        dtype=np.float64,
    )
    gains = np.asarray(
        [channel["steady_state_gain"] for row in rows for channel in row["prefix_moment_channels"]],
        dtype=np.float64,
    )
    return {
        "prefix_groups": len(rows),
        "q_over_r_quantiles": np.quantile(ratios, [0, 0.1, 0.5, 0.9, 1]).tolist(),
        "gain_quantiles": np.quantile(gains, [0, 0.1, 0.5, 0.9, 1]).tolist(),
    }


def main() -> None:
    """Run the hash-bound grade after prediction generation and review."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--predictions", type=Path, required=True)
    parser.add_argument("--prediction-receipt", type=Path, required=True)
    parser.add_argument("--preflight-output", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = main_grade(
        args.root,
        args.predictions,
        args.prediction_receipt,
        args.preflight_output,
        args.output,
    )
    print(
        json.dumps(
            {
                "status": "graded",
                "scores_wp": result["scores_wp"],
                "delta_vs_raw_wp": result["delta_vs_raw_wp"],
            }
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
