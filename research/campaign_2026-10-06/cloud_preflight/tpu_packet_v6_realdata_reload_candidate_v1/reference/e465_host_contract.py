"""Pure standard-library contracts for the E465 TPU worker.

These functions deliberately avoid importing JAX, NumPy, PyTorch, or data
readers. They make the registered fold/order/counter invariants reviewable on
a host without loading the training stack.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from dataclasses import dataclass

TRAIN_GROUPS = 10_535
FIT_VALID_GROUPS = 1_405
EVALUATION_GROUPS = 468
FIT_GROUPS = TRAIN_GROUPS + FIT_VALID_GROUPS
BATCH_SIZE = 32
SEQUENCE_ROWS = 20_000
CHUNK_ROWS = 1_000
EPOCH = 0
SEED = 3
BAD_TRAIN_GROUP = 528


@dataclass(frozen=True)
class EpochContract:
    """Derived counts for one fixed shuffled fit epoch."""

    fit_groups: int
    batch_size: int
    full_batches: int
    dropped_groups: int
    chunks_per_batch: int
    attempts_per_arm: int
    scheduled_steps: tuple[int, ...]
    unused_post_last_schedule_index: int


def validate_fold_membership(
    train_groups: Iterable[int],
    fit_valid_groups: Iterable[int],
    evaluation_groups: Iterable[int],
) -> tuple[tuple[int, ...], tuple[int, ...], tuple[int, ...]]:
    """Check registered cardinalities, split disjointness, and the TRAIN hole."""
    train = tuple(map(int, train_groups))
    valid_fit = tuple(map(int, fit_valid_groups))
    evaluation = tuple(map(int, evaluation_groups))
    for name, groups in (("TRAIN", train), ("fit VALID", valid_fit), ("evaluation", evaluation)):
        if len(groups) != len(set(groups)):
            raise ValueError(f"duplicate row group in {name}")
        if any(group < 0 for group in groups):
            raise ValueError(f"negative row group in {name}")
    if len(train) != TRAIN_GROUPS or BAD_TRAIN_GROUP in train:
        raise ValueError(
            "TRAIN membership differs from the registered clean fold or includes group 528"
        )
    if len(valid_fit) != FIT_VALID_GROUPS or len(evaluation) != EVALUATION_GROUPS:
        raise ValueError("VALID membership differs from the registered fit/evaluation counts")
    # Parquet row-group indices are split-local: TRAIN:0 and VALID:0 are
    # different sequences. Cross-split integer equality is therefore legal.
    if set(valid_fit) & set(evaluation):
        raise ValueError("fit VALID and evaluation membership overlap")
    return train, valid_fit, evaluation


def validate_epoch_batches(
    batches: Sequence[Sequence[tuple[str, int]]],
    fit_membership: Iterable[tuple[str, int]],
    *,
    batch_size: int = BATCH_SIZE,
    sequence_rows: int = SEQUENCE_ROWS,
    chunk_rows: int = CHUNK_ROWS,
) -> EpochContract:
    """Validate the exact complete-batch order and derive optimizer counters.

    The caller supplies the shuffled order generated by the bridge's seeded
    sampler. This function verifies order preservation, uniqueness, domain,
    and drop-last cardinality without depending on the sampler implementation.
    """
    expected = tuple((str(split), int(group)) for split, group in fit_membership)
    flattened = tuple((str(split), int(group)) for batch in batches for split, group in batch)
    if len(expected) != len(set(expected)):
        raise ValueError("fit membership contains duplicate split/group pairs")
    if len(flattened) != len(set(flattened)):
        raise ValueError("epoch order duplicates a fit sequence")
    if not set(flattened).issubset(set(expected)):
        raise ValueError("epoch order contains a sequence outside TRAIN plus fit VALID")
    if tuple(len(batch) for batch in batches) != (batch_size,) * len(batches):
        raise ValueError("epoch batches must all be complete; remainder is drop_last")
    if len(flattened) != (len(expected) // batch_size) * batch_size:
        raise ValueError("epoch batches do not contain the expected drop_last prefix size")
    chunks = sequence_rows // chunk_rows
    if chunks * chunk_rows != sequence_rows:
        raise ValueError("sequence length must be an exact multiple of chunk rows")
    full_batches = len(expected) // batch_size
    attempts = full_batches * chunks
    return EpochContract(
        fit_groups=len(expected),
        batch_size=batch_size,
        full_batches=full_batches,
        dropped_groups=len(expected) - full_batches * batch_size,
        chunks_per_batch=chunks,
        attempts_per_arm=attempts,
        scheduled_steps=tuple(range(attempts)),
        unused_post_last_schedule_index=attempts,
    )


def validate_sequence_domain(
    *,
    sequence_rows: int,
    chunk_rows: int,
    official_first_scored_row: int,
    all_valid_groups: int,
    evaluation_groups: int,
) -> None:
    """Enforce sequence/chunk and prediction/evaluation dimensions."""
    if sequence_rows != 20_000 or chunk_rows != 1_000:
        raise ValueError("E465 requires 20,000-row sequences and 1,000-row chunks")
    if sequence_rows % chunk_rows:
        raise ValueError("chunking must cover the sequence exactly")
    if official_first_scored_row != 99:
        raise ValueError("official scoring begins at row 99")
    if all_valid_groups != 1_873 or evaluation_groups != 468:
        raise ValueError("prediction export/evaluation dimensions differ from fold 0")


def adamw_scalar_step(
    parameter: float,
    gradient: float,
    first_moment: float,
    second_moment: float,
    step: int,
    *,
    learning_rate: float,
    beta1: float,
    beta2: float = 0.999,
    weight_decay: float = 0.01,
    epsilon: float = 1e-8,
) -> tuple[float, float, float]:
    """One FP32-scalar AdamW update matching the staged JAX implementation.

    Bias correction uses the current dynamic beta1 raised to the global step,
    matching PyTorch AdamW when the optimizer group's beta1 is changed before
    each ``step()`` call.
    """
    if step < 1:
        raise ValueError("step is one-based and must be positive")
    if not 0 <= beta1 < 1 or not 0 <= beta2 < 1:
        raise ValueError("Adam betas must be in [0, 1)")
    if learning_rate < 0 or weight_decay < 0 or epsilon <= 0:
        raise ValueError("invalid AdamW scalar hyperparameter")
    if not all(
        map(
            _finite,
            (
                parameter,
                gradient,
                first_moment,
                second_moment,
                learning_rate,
                beta1,
                beta2,
                weight_decay,
                epsilon,
            ),
        )
    ):
        raise ValueError("AdamW scalar inputs must be finite")
    m = beta1 * first_moment + (1.0 - beta1) * gradient
    v = beta2 * second_moment + (1.0 - beta2) * gradient * gradient
    m_hat = m / (1.0 - beta1**step)
    v_hat = v / (1.0 - beta2**step)
    updated = parameter - learning_rate * (
        m_hat / (v_hat**0.5 + epsilon) + weight_decay * parameter
    )
    return updated, m, v


def _finite(value: float) -> bool:
    """Check finiteness without importing math at module users' call sites."""
    return value == value and value not in (float("inf"), float("-inf"))
